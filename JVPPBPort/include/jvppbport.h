// layouts.c: short screens (menus, bonus stages...) rearranged for the tall
// canvas. A layout is a list of pieces: a rectangle of the GBA screen, which
// of its layers to take, and where it goes on the canvas. The rest of the
// canvas is filled with a repeated patch of one background (or an image).
#define PORT_LAYER_BG(n) (1 << (n))
#define PORT_LAYER_OBJ   (1 << 4)
#define PORT_LAYER_ALL   0x1F
struct __attribute__((aligned(4))) PortLayoutPiece
{
    int16_t sx, sy, w, h;  // source rectangle on the GBA screen
    int16_t dx, dy;        // its place on the canvas
    uint8_t layers;        // PORT_LAYER_* taken from the source rectangle
    uint8_t fillUnder;     // the fill background shows under it (else the backdrop color)
    uint8_t opaqueObjOnly; // with PORT_LAYER_OBJ: only sprites that aren't half see-through
    int16_t bgX;           // if not 0: the backgrounds' map x at the rectangle's left edge,
                           // minus 1 (the game's own scroll is ignored)
    uint8_t darken;        // darkened by this much (0-16, like the GBA's fade)
    int16_t dh;            // drawn this tall, the source lines repeated; 0: h
};
// A patch of one background repeated over a rectangle of the canvas,
// drawn over the fill.
struct __attribute__((aligned(4))) PortLayoutTile
{
    int8_t bg;
    int16_t mapX, mapY, w, h;  // the patch, in background map pixels (w, h <= 64)
    int16_t dx, dy, dw, dh;    // the canvas rectangle it covers
};
// A picture (or, with pixels NULL, a plain rectangle of `color`) drawn on
// the canvas over the fill, under the pieces.
struct __attribute__((aligned(4))) PortLayoutImage
{
    const uint32_t *pixels;  // 0xAARRGGBB, w x h; NULL: a rectangle
    uint32_t color;
    int16_t w, h;            // size of the source picture (or rectangle)
    int16_t dx, dy;          // its place on the canvas
    int16_t dw, dh;          // drawn at this size (pixels averaged); 0: w, h
    uint16_t brightness;     // 256 = as is
};
struct __attribute__((aligned(4))) PortLayout
{
    // Fill pattern: this background's pixels in the screen rectangle
    // (fillX, fillY, fillW, fillH), repeated over the canvas. fillBg < 0: none.
    int8_t fillBg;
    int16_t fillX, fillY, fillW, fillH;
    // Or an image under everything (0xAARRGGBB, the canvas's size), or NULL.
    const uint32_t *image;
    int pieceCount;
    const struct PortLayoutPiece *pieces;
    int imageCount;
    const struct PortLayoutImage *images;
    int tileCount;
    const struct PortLayoutTile *tiles;
};
